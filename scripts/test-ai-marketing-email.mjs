#!/usr/bin/env node
/**
 * Test the AI Marketing page (direct-marketing API) and send a test campaign
 * email through the exact pipeline the page uses.
 *
 * The AI Marketing page's email dispatch posts a payload with
 * `scenario: "email_marketing"` to the unified Make.com router, which relays it
 * to Resend (see docs/make-blueprint-marketing-dispatcher.json). This script
 * does the same thing so a real email can be delivered as an end-to-end test.
 *
 * Usage:
 *   node --env-file=.env scripts/test-ai-marketing-email.mjs [recipient]
 *
 * The recipient defaults to nefferoneff@gmail.com. The Make webhook URL comes
 * from MAKE_WEBHOOK_URL — never hardcode it here.
 */

const WORKER_URL =
  process.env.WORKER_URL?.trim() || "https://findmaid.wow-aisolution.workers.dev";
const WEBHOOK_URL = process.env.MAKE_WEBHOOK_URL?.trim() || "";
const RECIPIENT = (process.argv[2] || "nefferoneff@gmail.com").trim();
const TIMEOUT_MS = 60_000;

let passed = 0;
let warnings = 0;
let failed = 0;

const log = (icon, msg) => console.log(`  ${icon} ${msg}`);

// ── 1. Probe the AI Marketing endpoints ──────────────────────────────────────
async function probe(name, path) {
  const url = `${WORKER_URL}${path}`;
  try {
    const res = await fetch(url, {
      headers: { "Content-Type": "application/json" },
      signal: AbortSignal.timeout(TIMEOUT_MS),
    });
    const status = res.status;

    // 401/403 = endpoint exists but is agency-admin gated (expected/healthy).
    if (status === 401 || status === 403) {
      log("✅", `${name} — endpoint live (${status}: auth required)`);
      passed++;
      return { ok: true, status };
    }

    if (status === 200) {
      let data = null;
      try {
        data = await res.json();
      } catch {
        data = null;
      }
      const preview = data ? ` ${JSON.stringify(data).slice(0, 120)}` : "";
      log("✅", `${name} — 200 OK${preview}`);
      passed++;
      return { ok: true, status, data };
    }

    if (status === 503) {
      log("⚠️", `${name} — endpoint live but a dependency is not configured (503)`);
      warnings++;
      return { ok: true, status };
    }

    log("⚠️", `${name} — unexpected status ${status}`);
    warnings++;
    return { ok: false, status };
  } catch (err) {
    log("❌", `${name} — ${err.message}`);
    failed++;
    return { ok: false, error: err.message };
  }
}

// ── 2. Send the marketing test email through the dispatcher ──────────────────
async function sendMarketingEmail() {
  if (!WEBHOOK_URL) {
    log("❌", "MAKE_WEBHOOK_URL is not set — cannot send the test email.");
    log(
      "ℹ️",
      "Run with the env file: node --env-file=.env scripts/test-ai-marketing-email.mjs",
    );
    failed++;
    return;
  }

  const subject = "AI Marketing — Test email from Helped";
  const message = [
    `Hi there,`,
    ``,
    `This is a test email generated by the AI Marketing page (Helped).`,
    `If you received it, the marketing email dispatch is working end to end.`,
    ``,
    `Goal: new_arrivals`,
    `Sent: ${new Date().toISOString()}`,
  ].join("\n");
  const html = `<div style="font-family:Arial,sans-serif;font-size:14px;line-height:1.6;color:#111827">
  <p>Hi there,</p>
  <p>This is a <strong>test email</strong> generated by the <strong>AI Marketing</strong> page (Helped). If you received it, the marketing email dispatch is working end to end.</p>
  <p style="color:#6b7280">Goal: new_arrivals &middot; Sent: ${new Date().toISOString()}</p>
</div>`;

  const payload = {
    scenario: "email_marketing",
    to: RECIPIENT,
    contactName: "Test Recipient",
    subject,
    goal: "new_arrivals",
    agencyName: "Helped",
    agencyPhone: "6591234567",
    maidHighlights: "Test helper",
    message,
    html,
  };

  console.log("");
  console.log(`  📧 Sending marketing test email → ${RECIPIENT}`);
  try {
    const res = await fetch(WEBHOOK_URL, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(payload),
      signal: AbortSignal.timeout(TIMEOUT_MS),
    });
    const body = await res.text().catch(() => "");
    if (res.ok) {
      log("✅", `Make dispatcher accepted the email request (HTTP ${res.status})`);
      if (body.trim()) console.log(`      Response: ${body.slice(0, 200)}`);
      passed++;
    } else {
      log("❌", `Make dispatcher returned HTTP ${res.status}`);
      if (body.trim()) console.log(`      Response: ${body.slice(0, 200)}`);
      failed++;
    }
  } catch (err) {
    log("❌", `Failed to reach the dispatcher — ${err.message}`);
    failed++;
  }
}

async function main() {
  console.log("===========================================================");
  console.log("  🧪 AI Marketing — feature test + email delivery test");
  console.log(`  Worker : ${WORKER_URL}`);
  console.log(`  To     : ${RECIPIENT}`);
  console.log("===========================================================\n");

  console.log("── 1. AI Marketing endpoints ──");
  await probe("Autonomous status", "/api/ai/direct-marketing/autonomous/status");
  await probe("Audience (all_contacts)", "/api/ai/direct-marketing/audience?type=all_contacts");
  await probe("Campaigns", "/api/ai/direct-marketing/campaigns");
  await probe("Autonomous scan", "/api/ai/direct-marketing/autonomous/scan");

  console.log("\n── 2. Marketing email dispatch ──");
  await sendMarketingEmail();

  console.log("\n===========================================================");
  console.log(`  📊 Results: ${passed} passed, ${warnings} warnings, ${failed} failed`);
  console.log("===========================================================");
  process.exit(failed > 0 ? 1 : 0);
}

main().catch((err) => {
  console.error("Unhandled error:", err);
  process.exit(1);
});
