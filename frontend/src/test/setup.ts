import "@testing-library/jest-dom";

// jsdom does not implement ResizeObserver. recharts' ResponsiveContainer calls
// it on mount, so without this stub any page that renders the dashboard chart
// (e.g. HomePage) throws "ResizeObserver is not defined" and the test fails.
class ResizeObserverStub {
  observe() {}
  unobserve() {}
  disconnect() {}
}

if (typeof globalThis.ResizeObserver === "undefined") {
  globalThis.ResizeObserver = ResizeObserverStub as unknown as typeof ResizeObserver;
}

Object.defineProperty(window, "matchMedia", {
  writable: true,
  value: (query: string) => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: () => {},
    removeListener: () => {},
    addEventListener: () => {},
    removeEventListener: () => {},
    dispatchEvent: () => {},
  }),
});
